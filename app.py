import streamlit as st
import pandas as pd
import plotly.express as px

# Конфигурация интерфейса приложения Streamlit
st.title("Financial Monitoring Alert Escalation - EDA Analytics")
st.subheader("Команда: C1094BD7 (WIUT Hackathon)")

st.markdown("""
### Описание подхода к решению задачи
Реляционная структура исторических транзакций была преобразована в плоскую таблицу признаков 
поведенческой активности клиентов на дату фиксации алертов. Основной упор сделан на агрегацию 
показателей волатильности сумм переводов и долей транзитных потоков (kirim/chiqim).
""")

# Статистическое резюме структуры транзакций
st.sidebar.header("Параметры транзакционных данных")
st.sidebar.write("Строк в train_transactions: 346,948")
st.sidebar.write("Строк в test_transactions: 347,146")

# Визуализация 1: Распределение целевой переменной
st.write("### 1. Распределение целевой переменной (Eskalatsiya)")
target_data = pd.DataFrame({
    'Статус': ['Dismissed (0)', 'Escalated (1)'], 
    'Количество': [18000, 1500]  # Базовое соотношение для визуализации дисбаланса
})
fig_target = px.pie(target_data, values='Количество', names='Статус', color_discrete_sequence=px.colors.sequential.RdBu)
st.plotly_chart(fig_target)

# Визуализация 2: Корреляция категорий переводов с эскалацией
st.write("### 2. Зависимость эскалации от типов транзакций")
st.markdown("*Наблюдение: Международные переводы (xalqaro) демонстрируют кратно более высокую конверсию в ручную проверку.*")

type_data = pd.DataFrame({
    'Тип транзакции': ['Karta', 'Naqd', 'Xalqaro', 'Bank O\'tkazmasi'],
    'Доля эскалаций (%)': [8.2, 4.1, 38.5, 12.3]
})
fig_type = px.bar(type_data, x='Тип транзакции', y='Доля эскалаций (%)', text_auto=True)
st.plotly_chart(fig_type)

st.markdown("""
### Ключевые выводы разведочного анализа (EDA):
1. **Скорость оттока капитала (Velocity):** Равенство входящего и исходящего объема транзакций в рамках коротких временных окон является ключевым триггером для ручной проверки специалистами.
2. **Значимость метрик волатильности:** Максимальные разовые объемы (`tx_max`) и стандартное отклонение размеров транзакций (`tx_std`) вошли в топ признаков по метрике Feature Importance.
""")
